  String? findAnswer(String question) {
    final lower = question.toLowerCase().trim();
    for (var entry in _faq.entries) {
      final keyWords = entry.key.replaceAll('؟', '').split(' ');
      final matchCount = keyWords.where((w) => lower.contains(w)).length;
      if (matchCount >= keyWords.length * 0.6) {
        return entry.value;
      }
    }
    return null;
  }

  List<String> get suggestions => [
